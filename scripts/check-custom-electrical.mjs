import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';

// Isolated browser storage; never imports fixtures into the user's session.
mkdirSync('.playwright-cli', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const sourceSection = '2 <Electrical>';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5173');
  await page.waitForFunction(() => window.__PANEL_STATE__);
  await page.locator('[data-left="library"]').click();
  await page.locator('#new-product').click();
  await page.locator('#lib-brand').fill('验收样例');
  await page.locator('#lib-sku').fill('RELAY-24');
  await page.locator('#lib-kind').selectOption('relay');
  await page.locator('#lib-channels').fill('2');
  await page.locator('#lib-protocol').fill('din');
  await page.locator('#lib-control-power').selectOption('24VDC');
  await page.locator('#lib-load-power').selectOption('LN');
  await page.locator('#lib-channel-amps').fill('10');
  await page.locator('#lib-channel-watts').fill('1000');
  await page.locator('#lib-total-watts').fill('8');
  await page.locator('#lib-consumption-value').fill('5');
  await page.locator('#lib-consumption-unit').selectOption('W');
  await page.locator('#lib-source').fill('https://example.com/fixture.pdf');
  await page.locator('#lib-source-file').fill('验收样例（非厂家数据）');
  await page.locator('#lib-source-pages').fill(sourceSection);
  await page.locator('#lib-save').click();
  await page.waitForFunction(() => window.__PANEL_STATE__.design().customProducts.some(p => p.sku === 'RELAY-24'));
  const product = await page.evaluate(() => window.__PANEL_STATE__.design().customProducts.find(p => p.sku === 'RELAY-24'));
  assert.equal(product.powerInput, '24VDC');
  assert.equal(product.loadPowerInput, 'LN');
  assert.equal(product.powerConsumptionW, 8);
  assert.deepEqual(product.busConsumption, { value: 5, unit: 'W' });
  await page.reload();
  await page.waitForFunction(() => window.__PANEL_STATE__);
  await page.locator('[data-left="library"]').click();
  await page.locator(`[data-product="${product.id}"]`).click();
  assert.ok((await page.locator('#modal-body').textContent()).includes(sourceSection), 'source section must render as text');
  await page.locator('#product-edit').click();
  assert.equal(await page.locator('#lib-control-power').inputValue(), '24VDC');
  assert.equal(await page.locator('#lib-channel-amps').inputValue(), '10');
  assert.equal(await page.locator('#lib-source-pages').inputValue(), sourceSection);
  await page.locator('#lib-channel-amps').fill('-1');
  await page.locator('#lib-save').click();
  assert.equal(await page.locator('#modal').evaluate(el => el.open), true);
  assert.equal(await page.evaluate(() => window.__PANEL_STATE__.design().customProducts.find(p => p.sku === 'RELAY-24').channelAmps), 10);
  await page.locator('#lib-channel-amps').fill('10');
  await page.locator('#modal').screenshot({ path: '.playwright-cli/custom-electrical-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.locator('#modal').evaluate(el => el.scrollWidth <= el.clientWidth + 2), 'dialog must not overflow horizontally');
  await page.locator('#lib-save').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '.playwright-cli/custom-electrical-mobile.png' });
  await page.locator('#lib-save').click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('#new-product').click();
  await page.locator('#lib-brand').fill('验收样例');
  await page.locator('#lib-sku').fill('PSU-24');
  await page.locator('#lib-kind').selectOption('psu');
  await page.locator('#lib-control-power').selectOption('LN');
  await page.locator('#lib-load-power').selectOption('none');
  await page.locator('#lib-psu-voltage').fill('24');
  await page.locator('#lib-psu-amps').fill('1');
  await page.locator('#lib-psu-watts').fill('100');
  await page.locator('#lib-save').click();
  assert.equal(await page.locator('#modal').evaluate(el => el.open), true);
  assert.equal(await page.evaluate(() => window.__PANEL_STATE__.design().customProducts.some(p => p.sku === 'PSU-24')), false);
  await page.locator('#lib-psu-watts').fill('24');
  await page.locator('#lib-save').click();
  const delivery = await page.evaluate(async () => {
    const core = await import('/src/core/domain.js');
    const { normalizeModule } = await import('/src/core/modules.js');
    const { buildDeliveryNet } = await import('/src/core/delivery-net.js');
    const { buildHandoverFiles } = await import('/src/core/handover.js');
    const { renderWiringTable } = await import('/src/view/documents/wiring-table.js');
    const { computeBusBudgets } = await import('/src/core/bus-budget.js');
    const d = core.createDefaultDesign();
    d.uiMode = 'full'; d.supply = 'single'; d.includeSpd = false;
    d.circuits = d.circuits.filter(c => c.voltage === 220).slice(0, 2);
    d.customProducts = window.__PANEL_STATE__.design().customProducts;
    const relay = d.customProducts.find(p => p.sku === 'RELAY-24'), psu = d.customProducts.find(p => p.sku === 'PSU-24');
    d.modules = [normalizeModule({ id: 'K1', productId: relay.id, feed: 'shared', feedCircuitId: d.circuits[1].id, channels: { 1: d.circuits[0].id } }), normalizeModule({ id: 'PS1', productId: psu.id })];
    d.buses = [{ id: 'DC1', type: 'dc', voltage: 24, budgetUnit: 'W', psuModuleIds: ['PS1'], deviceModuleIds: ['K1'] }];
    const loaded = core.validateDesign(JSON.parse(JSON.stringify(d)));
    const assembly = core.buildAssembly(loaded), net = core.buildWiring(loaded, assembly);
    const projected = buildDeliveryNet(loaded, assembly, net);
    const html = renderWiringTable({ net: projected });
    const files = buildHandoverFiles({ design: loaded, net });
    const budget = computeBusBudgets(loaded, loaded.customProducts)[0];
    const mismatch = structuredClone(loaded);
    mismatch.customProducts.find(p => p.sku === 'PSU-24').psuOutput.voltage = 12;
    mismatch.buses[0].voltage = 12;
    return { budget, mismatchedDc: core.buildWiring(mismatch).wires.filter(w => w.class === 'dc').length, wires: net.wires.filter(w => w.to.startsWith('K1:')), html, csv: files['端子接线表.csv'], saved: JSON.parse(files['方案.json']).customProducts[0] };
  });
  assert.ok(delivery.wires.some(w => w.to === 'K1:DC+' && w.from === 'PS1:DC+' && w.class === 'dc'));
  assert.ok(delivery.wires.some(w => w.to === 'K1:L_IN' && w.class === 'power'));
  for (const end of ['K1:DC+', 'K1:DC-', 'K1:L_IN', 'K1:N_IN']) {
    assert.ok(delivery.html.includes(end), `PDF source missing ${end}`);
    assert.ok(delivery.csv.includes(end), `CSV missing ${end}`);
  }
  assert.equal(delivery.saved.source.pages, sourceSection);
  assert.equal(delivery.budget.capacity, 24);
  assert.equal(delivery.budget.used, 5);
  assert.equal(delivery.mismatchedDc, 0);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'PASS', checks: ['form save/reload/edit', 'invalid rating rejected', 'mobile dialog', 'PSU output conflict rejected', 'PSU budget', 'voltage mismatch rejected', 'separate DC and load wiring', 'PDF/CSV endpoints', 'source retained'], errors }));
} finally {
  await browser.close();
}
